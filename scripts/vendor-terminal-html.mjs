// Regenerates src/lib/terminal-vendor.generated.ts from the pristine xterm.js
// dist files vendored under assets/terminal/. Re-run after upgrading xterm:
//   node scripts/vendor-terminal-html.mjs
// The generated module holds the vendor sources as plain string constants so
// the WebView HTML shell (src/lib/terminal-html.ts) can inline them — the
// phone must render a terminal with no network access. Nothing here runs in
// the app; plain node only.
import { readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const dir = join(root, "assets", "terminal")

const css = readFileSync(join(dir, "xterm.css"), "utf8")
const js = readFileSync(join(dir, "xterm.js"), "utf8")
const fit = readFileSync(join(dir, "addon-fit.js"), "utf8")

for (const [name, text] of [["xterm.js", js], ["addon-fit.js", fit]]) {
  if (text.includes("</script")) throw new Error(`${name} contains "</script" — inline embedding is unsafe`)
}
if (css.includes("</style")) throw new Error('xterm.css contains "</style" — inline embedding is unsafe')

const out = `// GENERATED by scripts/vendor-terminal-html.mjs — do not edit by hand.
// Pristine copies live under assets/terminal/ (@xterm/xterm + @xterm/addon-fit).
export const XTERM_CSS: string = ${JSON.stringify(css)}
export const XTERM_JS: string = ${JSON.stringify(js)}
export const FIT_JS: string = ${JSON.stringify(fit)}
`
writeFileSync(join(root, "src", "lib", "terminal-vendor.generated.ts"), out)
console.log(`wrote src/lib/terminal-vendor.generated.ts (${out.length} bytes)`)
